#!/usr/bin/env node

import fs from 'fs/promises';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const BASE = 'https://viewunitysystem.github.io/OnAirMulTiMedia';
const urls = [
  '/',
  '/info.html',
  '/nomadic_swipe_nemo.html',
  '/test-dashboard.html',
  '/client.html',
  '/overlay.html',
  '/blueprints.html',
  '/manifest.html',
  '/regulatory.html',
  '/audit-export.html',
  '/settings/settings-panel.html',
  '/telemetry/telemetry-dashboard.html',
  '/web-remote/controller.html',
  '/web-remote/display.html',
  '/test.html',
  '/docs/index.html',
  '/o22/',
  '/o66/'
];

async function checkUrl(url) {
  try {
    const response = await fetch(BASE + url);
    return {
      url: url,
      status: response.status,
      ok: response.ok,
      statusText: response.statusText,
      timestamp: new Date().toISOString()
    };
  } catch (error) {
    return {
      url: url,
      status: 0,
      ok: false,
      error: error.message,
      timestamp: new Date().toISOString()
    };
  }
}

async function runHealthcheck() {
  console.log('🔍 Starting URL Healthcheck...');
  console.log(`Base URL: ${BASE}`);
  console.log(`Checking ${urls.length} URLs...\n`);

  const results = [];
  let successCount = 0;
  let errorCount = 0;

  for (const url of urls) {
    const result = await checkUrl(url);
    results.push(result);
    
    if (result.ok) {
      console.log(`✅ ${url} - ${result.status} ${result.statusText}`);
      successCount++;
    } else {
      console.log(`❌ ${url} - ${result.status} ${result.statusText || result.error}`);
      errorCount++;
    }
    
    // Rate limiting
    await new Promise(resolve => setTimeout(resolve, 100));
  }

  const summary = {
    timestamp: new Date().toISOString(),
    baseUrl: BASE,
    totalUrls: urls.length,
    successCount,
    errorCount,
    successRate: Math.round((successCount / urls.length) * 100),
    results
  };

  // Ensure audit directory exists
  const auditDir = join(__dirname, '..', 'audit');
  try {
    await fs.mkdir(auditDir, { recursive: true });
  } catch (error) {
    // Directory might already exist
  }

  // Write results
  await fs.writeFile(
    join(auditDir, 'url-healthcheck.json'),
    JSON.stringify(summary, null, 2)
  );

  // Write markdown report
  const markdownReport = `# URL Healthcheck Report

**Generated:** ${summary.timestamp}
**Base URL:** ${BASE}
**Success Rate:** ${summary.successRate}% (${successCount}/${urls.length})

## Summary

- ✅ **Success:** ${successCount} URLs
- ❌ **Errors:** ${errorCount} URLs
- 📊 **Success Rate:** ${summary.successRate}%

## Detailed Results

| URL | Status | Result |
|-----|--------|--------|
${results.map(r => `| ${r.url} | ${r.status} | ${r.ok ? '✅ OK' : '❌ Error'} |`).join('\n')}

## Failed URLs

${results.filter(r => !r.ok).map(r => `- **${r.url}**: ${r.status} ${r.statusText || r.error}`).join('\n')}

---
*Generated by OnAirMulTiMedia URL Healthcheck System*
`;

  await fs.writeFile(
    join(auditDir, 'url-healthcheck.md'),
    markdownReport
  );

  console.log('\n📊 Healthcheck Summary:');
  console.log(`✅ Success: ${successCount}/${urls.length} (${summary.successRate}%)`);
  console.log(`❌ Errors: ${errorCount}`);
  console.log(`📁 Reports saved to: audit/url-healthcheck.json & .md`);

  if (errorCount > 0) {
    console.log('\n🚨 Failed URLs:');
    results.filter(r => !r.ok).forEach(r => {
      console.log(`   ${r.url}: ${r.status} ${r.statusText || r.error}`);
    });
  }

  return summary;
}

// Run if called directly
if (import.meta.url === `file://${process.argv[1]}`) {
  runHealthcheck().catch(error => {
    console.error('❌ Healthcheck failed:', error);
    process.exit(1);
  });
}

export { runHealthcheck, checkUrl };
