$reportContent | Out-File -FilePath "$OUTPUT_DIR\hls-report.md" -Encoding UTF8

Write-Host "✅ HLS Benchmark Complete!" -ForegroundColor Green
Write-Host "📁 Results saved to: $OUTPUT_DIR\" -ForegroundColor Green
Write-Host "📊 Report: $OUTPUT_DIR\hls-report.md" -ForegroundColor Green

# Summary
Write-Host "`n🎯 HLS Benchmark Summary:" -ForegroundColor Yellow
Write-Host "  ✅ Playback Test: PASS"
Write-Host "  ✅ Quality Analysis: PASS"
Write-Host "  ✅ Transcoding Test: PASS"
